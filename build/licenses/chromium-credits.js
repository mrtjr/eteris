// Extrai a página de créditos do Chromium (chrome://credits, gerada pelo licenses.py do Chromium) do
// resources.pak do CEF. Os recursos estão comprimidos em brotli (prefixo 0x1e 0x9b + 6 bytes de tamanho).
// Uso: node chromium-credits.js <resources.pak> <saída.html>
const fs = require('fs');
const zlib = require('zlib');

const [pakPath, outPath] = process.argv.slice(2);
const pak = fs.readFileSync(pakPath);
if (pak.readUInt32LE(0) !== 5) throw new Error('Formato de .pak inesperado (só a versão 5 é suportada)');
const count = pak.readUInt16LE(8);
const table = 12;

for (let i = 0; i < count; i++) {
  const start = pak.readUInt32LE(table + i * 6 + 2);
  const end = pak.readUInt32LE(table + (i + 1) * 6 + 2);
  const blob = pak.subarray(start, end);
  if (blob[0] !== 0x1e || blob[1] !== 0x9b) continue;
  let html;
  try { html = zlib.brotliDecompressSync(blob.subarray(8)); } catch { continue; }
  if (!html.subarray(0, 64).toString('utf8').startsWith('<!-- Generated by licenses.py')) continue;
  fs.writeFileSync(outPath, html);
  console.log(`créditos do Chromium: ${html.length} bytes`);
  process.exit(0);
}
throw new Error('Não encontrei a página de créditos no resources.pak');
